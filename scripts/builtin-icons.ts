// Writes src/lib/builtin-icons-data.ts: the drawings of the built-in icons named in
// src/lib/builtin-icon-names.ts, taken from lucide-react (ISC license). Run after changing that list
// or upgrading lucide-react:
//   pnpm tsx scripts/builtin-icons.ts
export {};

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { BUILTIN_ICON_NAMES } from "../src/lib/builtin-icon-names";

const dir = join(process.cwd(), "node_modules/lucide-react/dist/esm/icons");

type IconNode = [string, Record<string, string | number>][];

/** An icon's drawing; a renamed icon's old name is a module re-exporting the new one. */
async function nodeOf(name: string): Promise<IconNode> {
  const file = join(dir, `${name}.mjs`);
  const source = readFileSync(file, "utf8");
  const alias = /export \{ default \} from '\.\/([\w-]+)\.mjs'/.exec(source);
  if (alias) return nodeOf(alias[1]);
  const mod = (await import(pathToFileURL(file).href)) as { __iconData?: { node: IconNode } };
  if (!mod.__iconData) throw new Error(`No drawing for "${name}"`);
  return mod.__iconData.node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
}

const lines: string[] = [];
for (const name of BUILTIN_ICON_NAMES) lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(await nodeOf(name))},`);

const version = (JSON.parse(readFileSync(join(process.cwd(), "node_modules/lucide-react/package.json"), "utf8")) as { version: string }).version;
const out = `// Generated by scripts/builtin-icons.ts from lucide-react ${version} (ISC license): don't edit by hand.
// The drawings of the built-in icons (lib/builtin-icon-names.ts), on a 24 by 24 grid, drawn with a
// 2-wide round stroke and no fill. Loaded only where such an icon shows (components/builtin-icon.tsx).

/** An icon's drawing: SVG elements with their attributes. */
export type BuiltinIconNode = readonly (readonly [tag: string, attrs: Readonly<Record<string, string | number>>])[];

export const BUILTIN_ICONS: Readonly<Record<string, BuiltinIconNode>> = {
${lines.join("\n")}
};
`;
writeFileSync(join(process.cwd(), "src/lib/builtin-icons-data.ts"), out);
console.log(`${BUILTIN_ICON_NAMES.length} icons written`);
process.exit(0);
