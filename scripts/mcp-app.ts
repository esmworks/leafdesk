// Writes src/server/mcp/app-bundle.ts: the script and style of show_database's view
// (src/mcp-app/database-view.ts and .css, with the MCP Apps SDK bundled in), which
// server/mcp/app-view.ts writes into the view's page. Run after changing the view or what it
// imports, or upgrading @modelcontextprotocol/ext-apps or esbuild (app-bundle.test.ts tells):
//   pnpm tsx scripts/mcp-app.ts
export {};

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build, type Plugin } from "esbuild";
import { optionPaletteCss, sourcesHash } from "../src/server/mcp/app-sources";

const root = process.cwd();
const ENTRY = "src/mcp-app/database-view.ts";
const STYLE = "src/mcp-app/database-view.css";

/**
 * zod's messages in every language, which the SDK's `import * as z` keeps in although only English
 * (loaded by zod's schemas themselves) is ever used: a fifth of the bundle.
 */
const noZodLocales: Plugin = {
  name: "no-zod-locales",
  setup(b) {
    b.onResolve({ filter: /^\.\.\/locales\/index\.js$/ }, (args) => (/[/\\]zod[/\\]/.test(args.importer) ? { path: "zod-locales", namespace: "empty" } : undefined));
    b.onLoad({ filter: /.*/, namespace: "empty" }, () => ({ contents: "export {};", loader: "js" }));
  },
};

const script = await build({
  entryPoints: [ENTRY],
  plugins: [noZodLocales],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  legalComments: "none",
  metafile: true,
  write: false,
  logLevel: "warning",
});
const style = await build({ entryPoints: [STYLE], bundle: true, minify: true, write: false, logLevel: "warning" });

const js = script.outputFiles[0].text.trim();
const css = style.outputFiles[0].text.trim() + optionPaletteCss(readFileSync(join(root, "src/app/globals.css"), "utf8"));
// Both go inline into the page: neither may end its element early or open a comment there.
if (/<\/script|<!--/i.test(js)) throw new Error("The view's script holds </script or <!--, which would break its page");
if (/<\/style/i.test(css)) throw new Error("The view's style holds </style, which would break its page");

// The repository's own files; packages count by their versions (app-sources.ts).
const sources = [...Object.keys(script.metafile.inputs).filter((path) => path.startsWith("src/")), STYLE].sort();
const out = `// Generated by scripts/mcp-app.ts from the files in DATABASE_VIEW_SOURCES: don't edit by hand.
// show_database's view as server/mcp/app-view.ts writes it into the view's page.

/** The files the bundle was made from; app-bundle.test.ts checks they still make it. */
export const DATABASE_VIEW_SOURCES: readonly string[] = ${JSON.stringify(sources)};
export const DATABASE_VIEW_HASH = ${JSON.stringify(sourcesHash(sources, root))};

export const DATABASE_VIEW_STYLE = ${JSON.stringify(css)};

export const DATABASE_VIEW_SCRIPT = ${JSON.stringify(js)};
`;
writeFileSync(join(root, "src/server/mcp/app-bundle.ts"), out);
console.log(`View written: script ${Math.round(js.length / 1024)} KB, style ${Math.round(css.length / 1024)} KB, from ${sources.length} files`);
process.exit(0);
