/** Same languages as the web app (src/i18n/config.ts), English first. */
export const STRINGS = { en, tr, de, es, fr, it, pt, pl, ru, uk, ar, he, fa, ja, ko, zh } satisfies Record<string, Strings>;

export type Locale = keyof typeof STRINGS;

const RTL = new Set<Locale>(["ar", "he", "fa"]);

export function isLocale(value: string): value is Locale {
  return Object.hasOwn(STRINGS, value);
}

/** The first of `preferred` (BCP 47 tags such as "pt-BR" or "zh-Hans-CN") Leafdesk speaks, else English. */
export function pickLocale(preferred: readonly string[]): Locale {
  for (const tag of preferred) {
    const language = tag.toLowerCase().split(/[-_]/)[0];
    if (isLocale(language)) return language;
  }
  return "en";
}

export function direction(locale: Locale): "rtl" | "ltr" {
  return RTL.has(locale) ? "rtl" : "ltr";
}

export function fill(text: string, values: Record<string, string>) {
  return text.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match);
}
